export function matchTierClasses(match) {
  if (match >= 85) return 'bg-accent-bg border-accent-border text-accent-ink';
  if (match >= 70) return 'bg-fill-2 border-border text-ink-3';
  return 'bg-fill-2 border-border text-ink-4';
}

export function initials(name) {
  return name
    .split(' ')
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0])
    .join('')
    .toUpperCase();
}
